export function getMaterialById(id: string): Material | undefined {
  return materials.find((m) => m.id === id);
}

/** average of published min/max tensile strength — used as the calculators' point estimate */
export function tensileAvg(m: Material): number {
  return (m.tensileMinMPa + m.tensileMaxMPa) / 2;
}
